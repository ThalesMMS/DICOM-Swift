// J2KHTConformantTables.swift
// ISO/IEC 15444-15 VLC + UVLC codebooks.
//
// Ports OpenJPH 0.26's `table0.h`, `table1.h` raw entries and the
// runtime `vlc_init_tables` / `uvlc_init_tables` code from
// `ojph_block_encoder.cpp`. The lookup tables are built lazily on
// first access and cached for the process lifetime.
//
// - `vlcTable0` / `vlcTable1`: 2048-entry `[UInt16]` indexed by
//   `(c_q << 8) | (rho << 4) | emb`; each entry packs
//   `(cwd << 8) | (cwd_len << 4) | e_k`.
// - `uvlcTable`: 75-entry U-value codebook indexed by the U value.

import Foundation

/// Raw VLC source record matching OpenJPH's `vlc_src_table`.
internal struct VLCSrc {
    let c_q: Int
    let rho: Int
    let u_off: Int
    let e_k: Int
    let e_1: Int
    let cwd: Int
    let cwd_len: Int

    init(_ c_q: Int, _ rho: Int, _ u_off: Int, _ e_k: Int,
         _ e_1: Int, _ cwd: Int, _ cwd_len: Int) {
        self.c_q = c_q
        self.rho = rho
        self.u_off = u_off
        self.e_k = e_k
        self.e_1 = e_1
        self.cwd = cwd
        self.cwd_len = cwd_len
    }
}

/// U-value codebook entry (prefix + suffix + optional extension bits).
internal struct UVLCEntry {
    let pre: UInt8
    let preLen: UInt8
    let suf: UInt8
    let sufLen: UInt8
    let ext: UInt8
    let extLen: UInt8
}

