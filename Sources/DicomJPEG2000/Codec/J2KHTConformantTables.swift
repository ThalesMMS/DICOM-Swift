internal func buildVLCLookup(from src: [VLCSrc]) -> [UInt16] {
    var tbl = [UInt16](repeating: 0, count: 2048)
    // Pre-computed popcount for 4-bit patterns.
    var popcnt = [Int](repeating: 0, count: 16)
    for i in 0..<16 {
        var v = i, c = 0
        while v != 0 { c += v & 1; v >>= 1 }
        popcnt[i] = c
    }
    for i in 0..<2048 {
        let c_q = i >> 8
        let rho = (i >> 4) & 0xF
        let emb = i & 0xF
        if ((emb & rho) != emb) || (rho == 0 && c_q == 0) {
            tbl[i] = 0
            continue
        }
        var best: VLCSrc? = nil
        if emb != 0 { // u_off = 1
            var bestOnes = -1
            for e in src where e.c_q == c_q && e.rho == rho && e.u_off == 1 {
                if (emb & e.e_k) == e.e_1 {
                    let ones = popcnt[e.e_k]
                    if ones >= bestOnes {
                        best = e
                        bestOnes = ones
                    }
                }
            }
        } else { // u_off = 0
            for e in src where e.c_q == c_q && e.rho == rho && e.u_off == 0 {
                best = e
                break
            }
        }
        guard let b = best else {
            // Mirrors OpenJPH's `assert(best_entry)`; unreachable given
            // valid source tables.
            preconditionFailure("VLC table lookup missed at index \(i)")
        }
        tbl[i] = UInt16((b.cwd << 8) | (b.cwd_len << 4) | b.e_k)
    }
    return tbl
}

/// Build the 75-entry UVLC codebook. Mirrors OpenJPH's
/// `uvlc_init_tables`.
internal func buildUVLCTable() -> [UVLCEntry] {
    var tbl = [UVLCEntry](repeating: UVLCEntry(pre: 0, preLen: 0, suf: 0,
                                                sufLen: 0, ext: 0, extLen: 0),
                          count: 75)
    tbl[0] = UVLCEntry(pre: 0, preLen: 0, suf: 0, sufLen: 0, ext: 0, extLen: 0)
    tbl[1] = UVLCEntry(pre: 1, preLen: 1, suf: 0, sufLen: 0, ext: 0, extLen: 0)
    tbl[2] = UVLCEntry(pre: 2, preLen: 2, suf: 0, sufLen: 0, ext: 0, extLen: 0)
    tbl[3] = UVLCEntry(pre: 4, preLen: 3, suf: 0, sufLen: 1, ext: 0, extLen: 0)
    tbl[4] = UVLCEntry(pre: 4, preLen: 3, suf: 1, sufLen: 1, ext: 0, extLen: 0)
    for i in 5..<33 {
        tbl[i] = UVLCEntry(pre: 0, preLen: 3,
                           suf: UInt8(i - 5), sufLen: 5,
                           ext: 0, extLen: 0)
    }
    for i in 33..<75 {
        tbl[i] = UVLCEntry(pre: 0, preLen: 3,
                           suf: UInt8(28 + (i - 33) % 4), sufLen: 5,
                           ext: UInt8((i - 33) / 4), extLen: 4)
    }
    return tbl
}

/// Build the 1024-entry decoder-side VLC reverse lookup from raw
/// source entries. Mirrors OpenJPH's `vlc_init_tables` in
/// `ojph_block_common.cpp`.
///
/// Index format: `(c_q << 7) | (next 7 bits of the reverse-VLC
/// stream)` — 3 bits of c_q context + 7 bits of codeword.
///
/// Entry format (16 bits):
///   bits 0..2:  cwd_len (1..7)
///   bit  3:     u_off   (0 or 1)
///   bits 4..7:  rho     (0..0xF)
///   bits 8..11: e_1     (0..0xF, matches encoder's e_1 field)
///   bits 12..15:e_k     (0..0xF, matches encoder's e_k field)
///
/// Collision policy: OpenJPH's initializer overwrites on match, so
/// the LAST matching source entry wins. We mirror that exactly (the
/// loop below assigns unconditionally when bits match).
internal func buildVLCDecoderLookup(from src: [VLCSrc]) -> [UInt16] {
    var tbl = [UInt16](repeating: 0, count: 1024)
    for i in 0..<1024 {
        let cwd = i & 0x7F
        let c_q = i >> 7
        for e in src where e.c_q == c_q {
            let mask = (1 << e.cwd_len) - 1
            if e.cwd == (cwd & mask) {
                tbl[i] = UInt16(
                    (e.e_k << 12) |
                    (e.e_1 << 8) |
                    (e.rho << 4) |
                    (e.u_off << 3) |
                    e.cwd_len)
            }
        }
    }
    return tbl
}

/// Lazily-initialized VLC / UVLC lookup tables. Building is pure so a
/// simple `let` binding suffices for thread-safe one-shot init.
internal let vlcTable0Conformant: [UInt16] = buildVLCLookup(from: vlcSrcTable0)

internal let vlcTable1Conformant: [UInt16] = buildVLCLookup(from: vlcSrcTable1)

/// Decoder-side reverse-lookup tables keyed by `(c_q, cwd_bits)`.
/// ~1 cycle per codeword lookup vs O(n) linear scan over the source
/// table. 15–20× decode speedup on blocks with many codewords.
internal let vlcDecoderTable0Conformant: [UInt16]
    = buildVLCDecoderLookup(from: vlcSrcTable0)

internal let vlcDecoderTable1Conformant: [UInt16]
    = buildVLCDecoderLookup(from: vlcSrcTable1)

internal let uvlcTableConformant: [UVLCEntry] = buildUVLCTable()
