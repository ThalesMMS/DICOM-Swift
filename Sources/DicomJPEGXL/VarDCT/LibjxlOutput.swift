    /// Scaled inverse matrix for an intensity target (`InitSIMDInverseMatrix`).
    struct OpsinInverse {
        let m: [Float]
        /// `OutputEncodingInfo::SetColorEncoding`: for a grey output the
        /// inverse opsin matrix is premultiplied by the sRGB luminances
        /// (`srgb_to_luma × inverse`, double precision), so every output
        /// channel is the luminance; then `InitSIMDInverseMatrix` scales
        /// by `255 / intensity_target`.
        init(intensityTarget: Float, gray: Bool = false) {
            let scale = 255.0 / intensityTarget
            if gray {
                let luminances: [Double] = [0.2126, 0.7152, 0.0722]
                let inv = LibjxlOutput.inverseMatrixDouble
                var row = [Double](repeating: 0, count: 3)
                for j in 0..<3 {
                    row[j] = luminances[0] * inv[j] + luminances[1] * inv[3 + j] + luminances[2] * inv[6 + j]
                }
                m = (row + row + row).map { Float($0) * scale }
            } else {
                m = LibjxlOutput.inverseMatrix.map { $0 * scale }
            }
        }
    }

    /// `XybToRgb`: XYB → linear RGB with the reference operation order.
    @inline(__always)
    static func xybToLinear(x: Float, y: Float, b: Float, inverse: OpsinInverse) -> (R: Float, G: Float, B: Float) {
        let gammaR = (y + x) - negBiasCbrt
        let gammaG = (y - x) - negBiasCbrt
        let gammaB = b - negBiasCbrt
        let mixedR = negBias.addingProduct(gammaR * gammaR, gammaR)
        let mixedG = negBias.addingProduct(gammaG * gammaG, gammaG)
        let mixedB = negBias.addingProduct(gammaB * gammaB, gammaB)
        let m = inverse.m
        var r = m[0] * mixedR
        var g = m[3] * mixedR
        var bl = m[6] * mixedR
        r = r.addingProduct(m[1], mixedG)
        g = g.addingProduct(m[4], mixedG)
        bl = bl.addingProduct(m[7], mixedG)
        r = r.addingProduct(m[2], mixedB)
        g = g.addingProduct(m[5], mixedB)
        bl = bl.addingProduct(m[8], mixedB)
        return (R: r, G: g, B: bl)
    }

    private static let p: [Float] = [-5.135152395e-04, 5.287254571e-03, 3.903842876e-01, 1.474205315e+00, 7.352629620e-01]
    private static let q: [Float] = [1.004519624e-02, 3.036675394e-01, 1.340816930e+00, 9.258482155e-01, 2.424867759e-02]

    /// The same arithmetic and FMA order, with four independent output pixels per vector.
    @inline(__always)
    static func xybToLinear(
        x: SIMD4<Float>, y: SIMD4<Float>, b: SIMD4<Float>, inverse: OpsinInverse
    ) -> (R: SIMD4<Float>, G: SIMD4<Float>, B: SIMD4<Float>) {
        let gammaR = (y + x) - negBiasCbrt
        let gammaG = (y - x) - negBiasCbrt
        let gammaB = b - negBiasCbrt
        let bias = SIMD4<Float>(repeating: negBias)
        let mixedR = bias.addingProduct(gammaR * gammaR, gammaR)
        let mixedG = bias.addingProduct(gammaG * gammaG, gammaG)
        let mixedB = bias.addingProduct(gammaB * gammaB, gammaB)
        let m = inverse.m
        let r = (mixedR * m[0]).addingProduct(mixedG, SIMD4(repeating: m[1])).addingProduct(mixedB, SIMD4(repeating: m[2]))
        let g = (mixedR * m[3]).addingProduct(mixedG, SIMD4(repeating: m[4])).addingProduct(mixedB, SIMD4(repeating: m[5]))
        let blue = (mixedR * m[6]).addingProduct(mixedG, SIMD4(repeating: m[7])).addingProduct(mixedB, SIMD4(repeating: m[8]))
        return (r, g, blue)
    }

    @inline(__always)
    static func srgbFromLinear(_ value: SIMD4<Float>) -> SIMD4<Float> {
        let signs = unsafeBitCast(value, to: SIMD4<UInt32>.self) & SIMD4(repeating: 0x80000000)
        let x = unsafeBitCast(unsafeBitCast(value, to: SIMD4<UInt32>.self) & SIMD4(repeating: 0x7fffffff), to: SIMD4<Float>.self)
        let s = x.squareRoot()
        var yp = SIMD4<Float>(repeating: p[4]), yq = SIMD4<Float>(repeating: q[4])
        for i in stride(from: 3, through: 0, by: -1) {
            yp = SIMD4(repeating: p[i]).addingProduct(yp, s)
            yq = SIMD4(repeating: q[i]).addingProduct(yq, s)
        }
        let magnitude = (x * 12.92).replacing(with: yp / yq, where: x .> SIMD4(repeating: 0.0031308))
        return unsafeBitCast(unsafeBitCast(magnitude, to: SIMD4<UInt32>.self) ^ signs, to: SIMD4<Float>.self)
    }

    /// `TF_SRGB::EncodedFromDisplay`: linear → sRGB-encoded (error ~5e-7).
    @inline(__always)
    static func srgbFromLinear(_ value: Float) -> Float {
        let sign = value.sign
        let x = abs(value)
        let s = x.squareRoot()
        var yp = p[4]
        var yq = q[4]
        yp = p[3].addingProduct(yp, s)
        yq = q[3].addingProduct(yq, s)
        yp = p[2].addingProduct(yp, s)
        yq = q[2].addingProduct(yq, s)
        yp = p[1].addingProduct(yp, s)
        yq = q[1].addingProduct(yq, s)
        yp = p[0].addingProduct(yp, s)
        yq = q[0].addingProduct(yq, s)
        let poly = yp / yq
        let magnitude = x > 0.0031308 ? poly : x * 12.92
        return sign == .minus ? -magnitude : magnitude
    }

    /// `MakeUnsigned<uint8_t>`: scale, dither, clamp, round to nearest even.
    @inline(__always)
    static func sample8(_ encoded: Float, x: Int, y: Int, channel c: Int) -> UInt8 {
        var v = encoded * 255
        v += dither[((y + c * 13) & 31) * 32 + ((x + c * 23) & 31)]
        v = max(0, min(v, 255))
        return UInt8(v.rounded(.toNearestOrEven))
    }

    /// Vector dither, clamp and round-to-even for four adjacent 8-bit samples.
    @inline(__always)
    static func sample8(_ encoded: SIMD4<Float>, x: Int, y: Int, channel c: Int) -> SIMD4<UInt8> {
        let row = ((y + c * 13) & 31) * 32
        let column = (x + c * 23) & 31
        let noise = SIMD4<Float>(dither[row + column], dither[row + ((column + 1) & 31)],
                                dither[row + ((column + 2) & 31)], dither[row + ((column + 3) & 31)])
        var v = encoded * 255 + noise
        v = v.replacing(with: SIMD4<Float>.zero, where: v .< SIMD4<Float>.zero)
        v = v.replacing(with: SIMD4<Float>(repeating: 255), where: v .> SIMD4<Float>(repeating: 255))
        v = v.rounded(.toNearestOrEven)
        // Concrete scalar casts avoid the generic SIMD floating-to-integer conversion path.
        return SIMD4<UInt8>(UInt8(v[0]), UInt8(v[1]), UInt8(v[2]), UInt8(v[3]))
    }

    /// `MakeUnsigned<uint16_t>` (no dithering): scale, clamp, round to nearest even.
    @inline(__always)
    static func sample(_ encoded: Float, maxValue: Float) -> UInt32 {
        var v = encoded * maxValue
        v = max(0, min(v, maxValue))
        return UInt32(v.rounded(.toNearestOrEven))
    }
